const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { crc32 } = require('zlib');

function createDummyZip(totalBytes) {
  const readmeContent = Buffer.from('This is a dummy test archive generated by Waterfall.\n');
  const readmeName = Buffer.from('README.txt');
  const readmeCrc = crc32(readmeContent);

  const manifestContent = Buffer.from(JSON.stringify({
    generator: 'Waterfall',
    targetSize: totalBytes,
    createdAt: new Date().toISOString()
  }, null, 2) + '\n');
  const manifestName = Buffer.from('manifest.json');
  const manifestCrc = crc32(manifestContent);

  const payloadName = Buffer.from('archive_payload.dat');

  const overhead = 
    (30 + readmeName.length + readmeContent.length) +
    (30 + manifestName.length + manifestContent.length) +
    (30 + payloadName.length) +
    (46 + readmeName.length) +
    (46 + manifestName.length) +
    (46 + payloadName.length) +
    22;

  if (totalBytes < overhead) {
    const buf = Buffer.alloc(totalBytes, 0);
    if (totalBytes >= 4) buf.write('PK\x03\x04', 0);
    return buf;
  }

  const payloadSize = totalBytes - overhead;
  const payloadBuf = Buffer.alloc(payloadSize);
  const payloadCrc = crc32(payloadBuf);

  const out = Buffer.alloc(totalBytes);
  let pos = 0;

  // 1. Local Header: README.txt
  const o1 = pos;
  out.writeUInt32LE(0x04034b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2; // version needed
  out.writeUInt16LE(0, pos); pos += 2; // general flag
  out.writeUInt16LE(0, pos); pos += 2; // method (0 = stored)
  out.writeUInt16LE(0, pos); pos += 2; // time
  out.writeUInt16LE(0, pos); pos += 2; // date
  out.writeUInt32LE(readmeCrc, pos); pos += 4;
  out.writeUInt32LE(readmeContent.length, pos); pos += 4; // comp size
  out.writeUInt32LE(readmeContent.length, pos); pos += 4; // uncomp size
  out.writeUInt16LE(readmeName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2; // extra field len
  readmeName.copy(out, pos); pos += readmeName.length;
  readmeContent.copy(out, pos); pos += readmeContent.length;

  // 2. Local Header: manifest.json
  const o2 = pos;
  out.writeUInt32LE(0x04034b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(manifestCrc, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt16LE(manifestName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  manifestName.copy(out, pos); pos += manifestName.length;
  manifestContent.copy(out, pos); pos += manifestContent.length;

  // 3. Local Header: archive_payload.dat
  const o3 = pos;
  out.writeUInt32LE(0x04034b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(payloadCrc, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt16LE(payloadName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  payloadName.copy(out, pos); pos += payloadName.length;
  // payload is zero-filled by Buffer.alloc
  pos += payloadSize;

  // Central Directory start
  const cdStart = pos;

  // CD 1: README.txt
  out.writeUInt32LE(0x02014b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2; // version made by
  out.writeUInt16LE(20, pos); pos += 2; // version needed
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2; // method
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(readmeCrc, pos); pos += 4;
  out.writeUInt32LE(readmeContent.length, pos); pos += 4;
  out.writeUInt32LE(readmeContent.length, pos); pos += 4;
  out.writeUInt16LE(readmeName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2; // extra len
  out.writeUInt16LE(0, pos); pos += 2; // comment len
  out.writeUInt16LE(0, pos); pos += 2; // disk start
  out.writeUInt16LE(0, pos); pos += 2; // internal attr
  out.writeUInt32LE(0, pos); pos += 4; // external attr
  out.writeUInt32LE(o1, pos); pos += 4; // offset of local header
  readmeName.copy(out, pos); pos += readmeName.length;

  // CD 2: manifest.json
  out.writeUInt32LE(0x02014b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(manifestCrc, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt16LE(manifestName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(0, pos); pos += 4;
  out.writeUInt32LE(o2, pos); pos += 4;
  manifestName.copy(out, pos); pos += manifestName.length;

  // CD 3: archive_payload.dat
  out.writeUInt32LE(0x02014b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(payloadCrc, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt16LE(payloadName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(0, pos); pos += 4;
  out.writeUInt32LE(o3, pos); pos += 4;
  payloadName.copy(out, pos); pos += payloadName.length;

  const cdSize = pos - cdStart;

  // End of Central Directory Record
  out.writeUInt32LE(0x06054b50, pos); pos += 4;
  out.writeUInt16LE(0, pos); pos += 2; // disk num
  out.writeUInt16LE(0, pos); pos += 2; // disk with CD
  out.writeUInt16LE(3, pos); pos += 2; // disk entries
  out.writeUInt16LE(3, pos); pos += 2; // total entries
  out.writeUInt32LE(cdSize, pos); pos += 4;
  out.writeUInt32LE(cdStart, pos); pos += 4;
  out.writeUInt16LE(0, pos); pos += 2; // comment length

  assert.strictEqual(pos, totalBytes, `Output size ${pos} must match requested size ${totalBytes}`);
  return out;
}

// Test 10 MB zip generation
const tenMb = 10 * 1024 * 1024;
const zipBuf = createDummyZip(tenMb);
console.log('Generated ZIP buffer size:', zipBuf.length, 'bytes (Requested:', tenMb, ')');
assert.strictEqual(zipBuf.length, tenMb);

// Test extracting with 7z binary
const testZipPath = path.join(__dirname, 'test_dummy.zip');
fs.writeFileSync(testZipPath, zipBuf);

const binaryResolver = require('../src/backend/binaryResolver');
const sevenZip = binaryResolver.get7zExecutable();
const { execSync } = require('child_process');

if (sevenZip) {
  const testOut = execSync(`"${sevenZip}" t "${testZipPath}"`).toString();
  assert(testOut.includes('Everything is Ok'), '7z test must succeed: ' + testOut);
  console.log('✓ 7-Zip successfully verified the generated ZIP archive integrity!');
}
try { fs.unlinkSync(testZipPath); } catch (_) {}
console.log('ALL DUMMY ZIP GENERATOR CHECKS PASSED!');
