const { crc32 } = require('zlib');

/**
 * Creates a valid ZIP archive of exact total byte size.
 * Contains README.txt, manifest.json, and archive_payload.dat.
 */
function createDummyZip(totalBytes) {
  const readmeContent = Buffer.from('This is a dummy test archive generated by Waterfall.\n');
  const readmeName = Buffer.from('README.txt');
  const readmeCrc = crc32(readmeContent);

  const manifestContent = Buffer.from(JSON.stringify({
    generator: 'Waterfall Download Suite',
    targetSize: totalBytes,
    createdAt: new Date().toISOString()
  }, null, 2) + '\n');
  const manifestName = Buffer.from('manifest.json');
  const manifestCrc = crc32(manifestContent);

  const payloadName = Buffer.from('archive_payload.dat');

  const overhead = 
    (30 + readmeName.length + readmeContent.length) +
    (30 + manifestName.length + manifestContent.length) +
    (30 + payloadName.length) +
    (46 + readmeName.length) +
    (46 + manifestName.length) +
    (46 + payloadName.length) +
    22;

  if (totalBytes < overhead) {
    const buf = Buffer.alloc(totalBytes, 0);
    if (totalBytes >= 4) buf.write('PK\x03\x04', 0);
    return buf;
  }

  const payloadSize = totalBytes - overhead;
  const payloadBuf = Buffer.alloc(payloadSize);
  const payloadCrc = crc32(payloadBuf);

  const out = Buffer.alloc(totalBytes);
  let pos = 0;

  // 1. Local Header: README.txt
  const o1 = pos;
  out.writeUInt32LE(0x04034b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(readmeCrc, pos); pos += 4;
  out.writeUInt32LE(readmeContent.length, pos); pos += 4;
  out.writeUInt32LE(readmeContent.length, pos); pos += 4;
  out.writeUInt16LE(readmeName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  readmeName.copy(out, pos); pos += readmeName.length;
  readmeContent.copy(out, pos); pos += readmeContent.length;

  // 2. Local Header: manifest.json
  const o2 = pos;
  out.writeUInt32LE(0x04034b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(manifestCrc, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt16LE(manifestName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  manifestName.copy(out, pos); pos += manifestName.length;
  manifestContent.copy(out, pos); pos += manifestContent.length;

  // 3. Local Header: archive_payload.dat
  const o3 = pos;
  out.writeUInt32LE(0x04034b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(payloadCrc, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt16LE(payloadName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  payloadName.copy(out, pos); pos += payloadName.length;
  // payload is zero-filled by Buffer.alloc
  pos += payloadSize;

  // Central Directory
  const cdStart = pos;

  // CD 1: README.txt
  out.writeUInt32LE(0x02014b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(readmeCrc, pos); pos += 4;
  out.writeUInt32LE(readmeContent.length, pos); pos += 4;
  out.writeUInt32LE(readmeContent.length, pos); pos += 4;
  out.writeUInt16LE(readmeName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(0, pos); pos += 4;
  out.writeUInt32LE(o1, pos); pos += 4;
  readmeName.copy(out, pos); pos += readmeName.length;

  // CD 2: manifest.json
  out.writeUInt32LE(0x02014b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(manifestCrc, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt32LE(manifestContent.length, pos); pos += 4;
  out.writeUInt16LE(manifestName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(0, pos); pos += 4;
  out.writeUInt32LE(o2, pos); pos += 4;
  manifestName.copy(out, pos); pos += manifestName.length;

  // CD 3: archive_payload.dat
  out.writeUInt32LE(0x02014b50, pos); pos += 4;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(20, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(payloadCrc, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt32LE(payloadSize, pos); pos += 4;
  out.writeUInt16LE(payloadName.length, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt32LE(0, pos); pos += 4;
  out.writeUInt32LE(o3, pos); pos += 4;
  payloadName.copy(out, pos); pos += payloadName.length;

  const cdSize = pos - cdStart;

  // End of Central Directory
  out.writeUInt32LE(0x06054b50, pos); pos += 4;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(0, pos); pos += 2;
  out.writeUInt16LE(3, pos); pos += 2;
  out.writeUInt16LE(3, pos); pos += 2;
  out.writeUInt32LE(cdSize, pos); pos += 4;
  out.writeUInt32LE(cdStart, pos); pos += 4;
  out.writeUInt16LE(0, pos); pos += 2;

  return out;
}

/**
 * Creates dummy data for any format of exact size
 */
function createDummyFileBuffer(format, totalBytes) {
  format = (format || 'bin').toLowerCase().replace('.', '');
  if (format === 'zip') {
    return createDummyZip(totalBytes);
  }

  const buf = Buffer.alloc(totalBytes);
  if (format === 'pdf' && totalBytes >= 30) {
    const header = Buffer.from('%PDF-1.4\n1 0 obj\n<<>>\nendobj\n');
    const trailer = Buffer.from('\nxref\n0 2\ntrailer\n<<>>\nstartxref\n9\n%%EOF\n');
    header.copy(buf, 0);
    trailer.copy(buf, totalBytes - trailer.length);
    return buf;
  }

  if (format === 'csv' && totalBytes >= 20) {
    const csvHdr = Buffer.from('id,name,value,timestamp\n1,dummy_item,100,');
    csvHdr.copy(buf, 0);
    return buf;
  }

  if (format === 'json' && totalBytes >= 20) {
    const jHdr = Buffer.from('{"status":"ok","dummy_data":"');
    const jTail = Buffer.from('"}');
    jHdr.copy(buf, 0);
    jTail.copy(buf, totalBytes - jTail.length);
    return buf;
  }

  return buf;
}

function parseSizeString(str) {
  if (!str) return 10 * 1024 * 1024;
  const match = String(str).trim().match(/^(\d+(?:\.\d+)?)\s*([a-z]+)?$/i);
  if (!match) return parseInt(str, 10) || 10 * 1024 * 1024;

  const val = parseFloat(match[1]);
  const unit = (match[2] || 'mb').toLowerCase();

  switch (unit) {
    case 'b': return Math.round(val);
    case 'k':
    case 'kb': return Math.round(val * 1024);
    case 'm':
    case 'mb': return Math.round(val * 1024 * 1024);
    case 'g':
    case 'gb': return Math.round(val * 1024 * 1024 * 1024);
    default: return Math.round(val * 1024 * 1024);
  }
}

module.exports = {
  createDummyZip,
  createDummyFileBuffer,
  parseSizeString
};
